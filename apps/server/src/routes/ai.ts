export const aiRoutes = new Hono<AppEnv>()

aiRoutes.post('/transcribe', async (c) => {
  const u = requireUser(c)
  const b = await body(c, z.object({ assetId: z.string().min(1), language: z.string().max(10).optional() }))
  const a = await loadAsset(b.assetId)
  await requireRole(u.id, a.workspaceId, 'editor')
  if (!whisperAvailable()) throw new HttpError(503, 'server', 'Transcription is not configured on this server')
  await assertQueueRoom(a.workspaceId)
  const j = await enqueue('ai.transcribe', b, { workspaceId: a.workspaceId, userId: u.id, projectId: a.projectId, message: `Transcribing ${a.name}` })
  return c.json(jobDto(j))
})

aiRoutes.post('/tts', async (c) => {
  const u = requireUser(c)
  const b = await body(c, z.object({ workspaceId: z.string().min(1), projectId: z.string().optional(), text: z.string().trim().min(1).max(10000), voice: z.string().max(80), speed: z.number().min(0.5).max(2).optional(), name: z.string().max(200).optional() }))
  await requireRole(u.id, b.workspaceId, 'editor')
  await assertProjectInWorkspace(b.projectId, b.workspaceId)
  const voice = validVoice(b.voice)
  await assertQueueRoom(b.workspaceId)
  // cloud: a cloned/designed voice is generated by the desktop that holds it
  if (isProfileVoice(voice) && ctx().config.mode !== 'desktop') return c.json(jobDto(await enqueueRelay({ ...b, voice, userId: u.id })))
  const j = await enqueue('ai.tts', { ...b, voice }, { workspaceId: b.workspaceId, userId: u.id, projectId: b.projectId, message: 'Generating voice' })
  return c.json(jobDto(j))
})

aiRoutes.get('/voices', async (c) => {
  const u = requireUser(c)
  // built-in Kokoro voices first, then this space's VoiceStudio voices (cloned / designed) with availability here
  const ws = c.req.query('workspaceId')
  return c.json([...VOICES, ...(await profileVoices(u.id, ws || undefined))])
})

const sampleJobs = new Map<string, Promise<string>>()
const SAMPLE_LINE: Record<string, string> = { a: 'Hi, I’m your narrator. Let’s turn this recording into something people want to watch.', b: 'Hello, I’ll be narrating your video today. Shall we make something worth watching?' }

aiRoutes.get('/voices/:id/sample', async (c) => {
  const u = requireUser(c)
  const id = c.req.param('id')
  if (isProfileVoice(id)) {
    // a VoiceStudio voice: its reference / design sample, served by the desktop that holds it
    const { loadVoiceProfile } = await import('./voice')
    const row = await loadVoiceProfile(profileIdOf(id))
    await requireRole(u.id, row.workspaceId, 'viewer')
    if (ctx().config.mode !== 'desktop' || !row.vsProfileId) throw new HttpError(404, 'not_found', 'Preview this voice in Producer Studio on the computer that made it')
    const { vsOk } = await import('../desktop/voicestudio/client')
    const res = await vsOk(`/profiles/${encodeURIComponent(row.vsProfileId)}/audio`, { timeoutMs: 120_000 })
    return new Response(res.body, { headers: { 'Content-Type': res.headers.get('content-type') ?? 'audio/wav', 'Cache-Control': 'private, max-age=60' } })
  }
  const v = VOICES.find((x) => x.id === id)
  if (!v) throw notFound('Unknown voice')
  const dir = path.join(ctx().config.dataDir, 'voice-samples')
  const file = path.join(dir, `${id}.wav`)
  if (!fs.existsSync(file)) {
    let p = sampleJobs.get(id)
    if (!p) {
      fs.mkdirSync(dir, { recursive: true })
      const tmp = `${file}.tmp.wav`
      p = tts
        .synthesize(`${SAMPLE_LINE[id[0]] ?? SAMPLE_LINE.a}`, tmp, { voice: id, speed: 1 })
        .then(() => {
          fs.renameSync(tmp, file)
          return file
        })
        .finally(() => sampleJobs.delete(id))
      sampleJobs.set(id, p)
    }
    await p
  }
  const buf = fs.readFileSync(file)
  return new Response(buf, { headers: { 'Content-Type': 'audio/wav', 'Content-Length': String(buf.length), 'Cache-Control': 'private, max-age=86400' } })
})

/** Workspace whose AI settings apply to the writer: the requested one (editor+), else the user's personal workspace. */
async function writerScope(userId: string, workspaceId: string | undefined): Promise<string | undefined> {
  if (ctx().config.mode === 'desktop') return undefined
  if (workspaceId) {
    await requireRole(userId, workspaceId, 'editor')
    return workspaceId
  }
  const rows = await ctx()
    .db.select({ id: workspaces.id, personal: workspaces.personal })
    .from(memberships)
    .innerJoin(workspaces, eq(workspaces.id, memberships.workspaceId))
    .where(eq(memberships.userId, userId))
  return (rows.find((r) => r.personal) ?? rows[0])?.id
}

aiRoutes.post('/write', async (c) => {
  const u = requireUser(c)
  const b = await body(c, z.object({ kind: z.enum(['voiceover', 'script', 'headline', 'caption', 'rewrite']), prompt: z.string().min(1).max(20000), context: z.string().max(50000).optional(), maxWords: z.number().int().min(1).max(5000).optional(), workspaceId: z.string().max(100).optional() }))
  const provider = await requireProvider(await writerScope(u.id, b.workspaceId), 'writer')
  limitAi(u.id)
  return streamSSE(c, async (stream) => {
    const ac = new AbortController()
    stream.onAbort(() => ac.abort())
    try {
      const text = await provider.write(b, (d) => void stream.writeSSE({ event: 'delta', data: JSON.stringify({ text: d }) }), ac.signal)
      await stream.writeSSE({ event: 'done', data: JSON.stringify({ text }) })
    } catch (err) {
      if (!ac.signal.aborted) {
        const e = err instanceof HttpError ? { error: err.message, code: err.code } : { error: 'AI request failed', code: 'server' }
        if (!(err instanceof HttpError)) log.error('ai write failed', { err })
        await stream.writeSSE({ event: 'error', data: JSON.stringify(e) })
      }
    }
  })
})

const BriefSchema = z.object({
  title: z.string().max(200),
  audience: z.string().max(500).default(''),
  goal: z.string().max(1000).default(''),
  tone: z.string().max(200).default('warm'),
  template: z.string().max(60).default('studio-dark'),
  voice: z.string().max(80).default('af_heart'),
  aspect: z.enum(['16:9', '9:16', '1:1']).default('16:9'),
  notes: z.string().max(4000).optional(),
  source: z.enum(['recordings', 'idea']).optional(),
  idea: z.string().max(20000).optional(),
  lengthSec: z.number().int().min(15).max(600).optional(),
  visualKinds: z.array(z.enum(['motion', 'diagram', 'image', 'stock', 'aiVideo'])).max(6).optional(),
})

aiRoutes.post('/produce/script', async (c) => {
  const u = requireUser(c)
  const b = await body(c, z.object({ projectId: z.string().min(1), assetIds: z.array(z.string()).max(20).default([]), brief: BriefSchema }))
  // recordings mode needs at least one; idea mode needs the idea (or at least a title)
  if (b.brief.source !== 'idea' && !b.assetIds.length) throw new HttpError(400, 'invalid', 'Add at least one recording, or make the video from an idea')
  if (b.brief.source === 'idea' && !(b.brief.idea?.trim() || b.brief.title.trim())) throw new HttpError(400, 'invalid', 'Describe the idea for the video')
  const row = await loadProjectRow(b.projectId)
  await requireRole(u.id, row.workspaceId, 'editor')
  await requireProvider(row.workspaceId, 'script')
  await assertQueueRoom(row.workspaceId)
  limitAi(u.id)
  const j = await enqueue('ai.produce.script', { ...b, brief: { ...b.brief, voice: validVoice(b.brief.voice) } }, { workspaceId: row.workspaceId, userId: u.id, projectId: row.id, message: 'Writing script' })
  return c.json(jobDto(j))
})

const SceneSchema = z.object({
  id: z.string().min(1).max(20),
  title: z.string().max(200),
  headline: z.string().max(300),
  narration: z.string().min(1).max(5000),
  footage: z.array(z.object({ assetId: z.string(), start: z.number().min(0), end: z.number().min(0) })).max(20),
  visuals: z.string().max(2000).optional(),
  visual: VisualSchema.optional(),
  voice: z.object({ assetId: z.string(), duration: z.number() }).optional(),
})

/**
 * The wizard's brief and script edits, saved to the project's `ai` as they're typed, so another tab or device resumes
 * them. Only `ai` changes (on the latest version): the timeline and everything else stay as they are.
 */
aiRoutes.put('/produce/draft', async (c) => {
  const u = requireUser(c)
  // a scene still being written may have no narration yet
  const DraftScene = SceneSchema.extend({ narration: z.string().max(5000) })
  const b = await body(c, z.object({ projectId: z.string().min(1), brief: BriefSchema, scenes: z.array(DraftScene).max(100), scriptBrief: BriefSchema.optional() }))
  const row = await loadProjectRow(b.projectId)
  await requireRole(u.id, row.workspaceId, 'editor')
  const brief = { ...b.brief, voice: validVoice(b.brief.voice) }
  const saved = await saveOnLatest(row.id, (cur) => ({
    ...cur,
    ai: { ...(cur.ai ?? {}), brief, script: { ...(cur.ai?.script ?? {}), scenes: b.scenes, ...(b.scriptBrief ? { brief: b.scriptBrief } : {}) } },
  }))
  return c.json({ version: saved.version })
})

/** What Producer AI can make for this space without recordings (which keys exist, whether stock footage is set up). */
aiRoutes.get('/produce/capabilities', async (c) => {
  const u = requireUser(c)
  const ws = c.req.query('workspaceId')
  if (!ws) throw new HttpError(400, 'invalid', 'workspaceId is required')
  await requireRole(u.id, ws, 'viewer')
  const caps = await generationCapabilities(ws)
  return c.json({ ...caps, kinds: await allowedVisualKinds(ws, ['motion', 'diagram', 'image', 'stock', 'aiVideo']), maxAiClips: MAX_AI_CLIPS } satisfies ProduceCapabilities)
})

aiRoutes.post('/produce/assemble', async (c) => {
  const u = requireUser(c)
  const b = await body(
    c,
    z.object({ projectId: z.string().min(1), scenes: z.array(SceneSchema).min(1).max(40), brief: BriefSchema.optional(), replace: z.boolean().optional(), intoCopy: z.boolean().optional() }),
  )
  const row = await loadProjectRow(b.projectId)
  await requireRole(u.id, row.workspaceId, 'editor')
  await assertQueueRoom(row.workspaceId)
  // assembling replaces the whole timeline: ask first when it holds edits made since the last assembly
  if (!b.replace && !b.intoCopy && editedSinceAssembly(row.doc)) {
    throw new HttpError(409, 'conflict', 'This project was edited since it was assembled. Assembling again replaces the whole timeline, including those edits.', { reason: 'edited' })
  }
  let target = row
  if (b.intoCopy) {
    const doc = withFreshIds(row.doc, uid('p'))
    doc.name = `${row.name} copy`.slice(0, 200)
    target = await insertProject({ workspaceId: row.workspaceId, userId: u.id, doc, kind: row.kind })
  }
  // the brief as it is on screen (voice, look, title): not the one the script was written from
  const brief = b.brief ? { ...b.brief, voice: validVoice(b.brief.voice) } : undefined
  const input: AssembleJobInput = { projectId: target.id, scenes: b.scenes, ...(brief ? { brief } : {}), base: timelineFingerprint(target.doc) }
  const j = await enqueue('ai.produce.assemble', { ...input }, { workspaceId: row.workspaceId, userId: u.id, projectId: target.id, message: 'Assembling' })
  return c.json(jobDto(j))
})

aiRoutes.post('/assistant', async (c) => {
  const u = requireUser(c)
  const b = await body(
    c,
    z.object({
      projectId: z.string().min(1),
      project: z.looseObject({ id: z.string(), tracks: z.array(z.unknown()), assets: z.record(z.string(), z.unknown()) }),
      playhead: z.number().min(0).default(0),
      selection: z.array(z.string()).default([]),
      messages: z.array(z.object({ role: z.enum(['user', 'assistant']), text: z.string().max(20000) })).min(1).max(100),
    }),
  )
  const row = await loadProjectRow(b.projectId)
  await requireRole(u.id, row.workspaceId, 'editor')
  const provider = await requireProvider(row.workspaceId, 'assistant')
  limitAi(u.id)
  const wsId = row.workspaceId
  const req = b as unknown as AssistantRequest
  return streamSSE(c, async (stream) => {
    const ac = new AbortController()
    stream.onAbort(() => ac.abort())
    const step = inlineContext({ id: 'assistant', kind: 'ai.transcribe', workspaceId: wsId, userId: u.id, projectId: row.id, input: {} }, ac.signal)
    const env = {
      transcribe: async (assetId: string) => {
        const a = await loadAsset(assetId)
        if (a.workspaceId !== wsId) throw notFound('Asset not found')
        return ensureTranscript(assetId, step)
      },
      tts: async (text: string, voice: string, speed: number) => {
        const r = await synthesizeToAsset({ workspaceId: wsId, userId: u.id, projectId: row.id, text, voice, speed }, step)
        return { asset: r.asset.asset, duration: r.duration }
      },
    }
    try {
      const result = await runAssistant(
        provider,
        { ...req, project: req.project as Project },
        env,
        {
          text: (d) => void stream.writeSSE({ event: 'text', data: JSON.stringify({ delta: d }) }),
          tool: (name, summary) => void stream.writeSSE({ event: 'tool', data: JSON.stringify({ name, summary }) }),
        },
        ac.signal,
      )
      await stream.writeSSE({ event: 'done', data: JSON.stringify(result) })
    } catch (err) {
      if (!ac.signal.aborted) {
        if (!(err instanceof HttpError)) log.error('assistant failed', { err })
        const e = err instanceof HttpError ? { error: err.message, code: err.code } : { error: err instanceof Error ? err.message : 'Assistant failed', code: 'server' }
        await stream.writeSSE({ event: 'error', data: JSON.stringify(e) })
      }
    }
  })
})
